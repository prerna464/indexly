/* ════════════════════════════════════════════
   UPDATE-USDINR-DATA.JS
   Builds assets/js/usdinr-data.js with daily USD/INR
   closes (INR per 1 USD) from 2016-08-01 to today.

   Run:  node update-usdinr-data.js      (Node 18+)
   Safe to re-run daily: it rewrites the whole file, so
   there are no duplicates and no regex editing.
   No API key needed (Yahoo Finance, symbol INR=X).
════════════════════════════════════════════ */

const fs   = require("fs");
const path = require("path");

const OUT_FILE = path.join(__dirname, "assets", "js", "usdinr-data.js");
const START    = "2016-08-01"; // a bit before your first index date (2016-08-15)

async function main() {
  const period1 = Math.floor(new Date(START + "T00:00:00Z").getTime() / 1000);
  const period2 = Math.floor(Date.now() / 1000);
  const url = `https://query1.finance.yahoo.com/v8/finance/chart/INR%3DX?period1=${period1}&period2=${period2}&interval=1d`;

  const res = await fetch(url, { headers: { "User-Agent": "Mozilla/5.0" } });
  if (!res.ok) throw new Error(`Yahoo returned HTTP ${res.status}`);
  const json = await res.json();

  const result = json.chart && json.chart.result && json.chart.result[0];
  if (!result) throw new Error("No data returned for INR=X");

  const ts     = result.timestamp;
  const closes = result.indicators.quote[0].close;

  const rows = [];
  const seen = new Set();
  for (let i = 0; i < ts.length; i++) {
    const c = closes[i];
    if (c === null || c === undefined) continue;     // skip placeholder rows
    if (c < 30 || c > 200) continue;                 // sanity check: bad tick
    const date = new Date(ts[i] * 1000).toISOString().slice(0, 10);
    if (seen.has(date)) continue;                    // keep one close per date
    seen.add(date);
    rows.push(`    { date: "${date}", close: ${Number(c.toFixed(4))} }`);
  }

  if (rows.length < 1000) throw new Error(`Only ${rows.length} rows, refusing to overwrite the file`);

  const text =
`// ════════════════════════════════════════════
// USD/INR DAILY CLOSES (INR per 1 USD)
// Auto-generated by update-usdinr-data.js, do not edit by hand.
// ════════════════════════════════════════════

const USDINR_DATA = {
  meta: { pair: "USD/INR", note: "INR per 1 USD, daily close" },
  series: [
${rows.join(",\n")}
  ]
};
`;

  fs.writeFileSync(OUT_FILE, text, "utf8");
  console.log(`✔ usdinr-data.js written: ${rows.length} rows (${START} to latest)`);
}

main().catch(err => { console.error("✘ FAILED —", err.message); process.exit(1); });